-- เพิ่มสิทธิ์ระดับ "ผู้จัดงาน" (organizer)
--
-- เดิมระบบมีสิทธิ์ 2 ระดับที่ใช้งานจริง คือผู้ดูแลระบบกับเจ้าหน้าที่หน้างาน
-- ไม่มีตรงกลางสำหรับคนที่ต้องดูแลงานทั้งงานแต่ไม่ควรเพิ่มหรือแก้บัญชีผู้ใช้
--
-- ⚠️ ห้ามเปลี่ยนชื่อหรือลบค่าเดิมในรายการนี้เด็ดขาด
--    PostgreSQL ไม่ยอมให้ลบค่าของ enum ที่มีแถวอ้างถึงอยู่
--    และคอลัมน์ users.role อ้างถึงค่าเหล่านี้ทุกแถว
--
-- ค่า viewer มีมาแต่เดิมและไม่เคยถูกใช้งานจริง จึงปล่อยไว้เฉย ๆ
-- การลบต้องสร้าง enum ใหม่แล้วย้ายข้อมูลทั้งตาราง ซึ่งเสี่ยงเกินประโยชน์ที่ได้

ALTER TYPE "user_role" ADD VALUE IF NOT EXISTS 'organizer';
